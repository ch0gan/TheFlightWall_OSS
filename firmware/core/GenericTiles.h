#pragma once
/*
Generic (non-airline) logo tiles compiled into the firmware: _CESSNA, _LIGHT,
_BIZJET, _PRIVATE, _HELI, _CARGO. Built-in copies win over /logos/ on LittleFS,
so changing one needs only a firmware upload, never an uploadfs.

Each tile has the same bytes as a /logos/*.rgb565 file: u16 width, u16 height,
then width*height RGB565 pixels, all little-endian.

The data lives in GenericTiles.cpp, generated by tools/gen_generic_tiles.py.
*/
#include <stddef.h>
#include <stdint.h>

// The tile for `key` (e.g. "_CESSNA"), or nullptr when there is no built-in one.
const uint8_t *builtinTile(const char *key, size_t &len);

// For listing them (web logo inventory).
size_t builtinTileCount();
const char *builtinTileKey(size_t i);
